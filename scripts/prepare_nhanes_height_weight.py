#!/usr/bin/env python3
"""Build the compact NHANES height/weight histogram used by the web app.

This is a development-only reproducibility script. It requires pandas and
NumPy; neither package is needed by the web application at runtime.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import textwrap
from pathlib import Path

import numpy as np
import pandas as pd


HEIGHT_DOMAIN = (124.0, 212.0)
WEIGHT_DOMAIN = (20.0, 275.0)
HEIGHT_BINS = 128
WEIGHT_BINS = 160


def weighted_quantile(values: np.ndarray, weights: np.ndarray, quantile: float) -> float:
    order = np.argsort(values)
    sorted_values = values[order]
    cumulative = np.cumsum(weights[order]) / weights.sum()
    index = min(int(np.searchsorted(cumulative, quantile)), len(sorted_values) - 1)
    return float(sorted_values[index])


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("body_measures", type=Path, help="CDC BMX_J.XPT file")
    parser.add_argument("demographics", type=Path, help="CDC DEMO_J.XPT file")
    parser.add_argument("output", type=Path, help="Generated TypeScript module")
    args = parser.parse_args()

    body = pd.read_sas(args.body_measures, format="xport")
    demographics = pd.read_sas(args.demographics, format="xport")
    merged = body[["SEQN", "BMXHT", "BMXWT"]].merge(
        demographics[["SEQN", "RIDAGEYR", "RIDEXPRG", "WTMEC2YR"]],
        on="SEQN",
        validate="one_to_one",
    )

    measured_adults = merged[
        (merged.RIDAGEYR >= 20)
        & merged.BMXHT.notna()
        & merged.BMXWT.notna()
        & merged.WTMEC2YR.notna()
        & (merged.WTMEC2YR > 0)
    ]
    known_pregnancies = int((measured_adults.RIDEXPRG == 1).sum())
    cohort = measured_adults[measured_adults.RIDEXPRG != 1].copy()

    weights = cohort.WTMEC2YR.to_numpy(dtype=np.float64)
    normalized_weights = weights / weights.sum()
    histogram, _, _ = np.histogram2d(
        cohort.BMXHT.to_numpy(),
        cohort.BMXWT.to_numpy(),
        bins=(HEIGHT_BINS, WEIGHT_BINS),
        range=(HEIGHT_DOMAIN, WEIGHT_DOMAIN),
        weights=normalized_weights,
    )
    # Runtime arrays are y-major: weight row, then height column.
    packed = np.asarray(histogram.T, dtype="<f4").ravel(order="C")
    encoded = base64.b64encode(packed.tobytes()).decode("ascii")
    chunks = textwrap.wrap(encoded, 100)

    mean_height = float(np.average(cohort.BMXHT, weights=weights))
    mean_weight = float(np.average(cohort.BMXWT, weights=weights))
    height_delta = cohort.BMXHT.to_numpy() - mean_height
    weight_delta = cohort.BMXWT.to_numpy() - mean_weight
    covariance = float(np.average(height_delta * weight_delta, weights=weights))
    height_variance = float(np.average(height_delta**2, weights=weights))
    weight_variance = float(np.average(weight_delta**2, weights=weights))
    correlation = covariance / np.sqrt(height_variance * weight_variance)
    height_p005 = weighted_quantile(cohort.BMXHT.to_numpy(), weights, 0.005)
    height_p995 = weighted_quantile(cohort.BMXHT.to_numpy(), weights, 0.995)
    weight_p005 = weighted_quantile(cohort.BMXWT.to_numpy(), weights, 0.005)
    weight_p995 = weighted_quantile(cohort.BMXWT.to_numpy(), weights, 0.995)

    chunk_lines = "\n".join(f'  "{chunk}",' for chunk in chunks)
    contents = f'''// Generated by scripts/prepare_nhanes_height_weight.py. Do not edit by hand.
// Source checksums make the transformation reproducible from the CDC XPT files.

export const NHANES_HEIGHT_DOMAIN: [number, number] = [{HEIGHT_DOMAIN[0]}, {HEIGHT_DOMAIN[1]}];
export const NHANES_WEIGHT_DOMAIN: [number, number] = [{WEIGHT_DOMAIN[0]}, {WEIGHT_DOMAIN[1]}];
export const NHANES_HEIGHT_BINS = {HEIGHT_BINS};
export const NHANES_WEIGHT_BINS = {WEIGHT_BINS};
export const NHANES_COHORT_SIZE = {len(cohort)};
export const NHANES_EXCLUDED_KNOWN_PREGNANCIES = {known_pregnancies};
export const NHANES_WEIGHTED_MEAN_HEIGHT_CM = {mean_height:.9f};
export const NHANES_WEIGHTED_MEAN_WEIGHT_KG = {mean_weight:.9f};
export const NHANES_WEIGHTED_CORRELATION = {correlation:.9f};
export const NHANES_HEIGHT_P005_CM = {height_p005:.9f};
export const NHANES_HEIGHT_P995_CM = {height_p995:.9f};
export const NHANES_WEIGHT_P005_KG = {weight_p005:.9f};
export const NHANES_WEIGHT_P995_KG = {weight_p995:.9f};
export const NHANES_BMX_SHA256 = "{sha256(args.body_measures)}";
export const NHANES_DEMO_SHA256 = "{sha256(args.demographics)}";

export const NHANES_WEIGHTED_HISTOGRAM_BASE64 = [
{chunk_lines}
].join("");
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(contents, encoding="utf-8")
    print(
        f"Wrote {args.output} from {len(cohort)} adults; "
        f"excluded {known_pregnancies} known pregnancies."
    )


if __name__ == "__main__":
    main()
