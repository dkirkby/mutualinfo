#!/usr/bin/env python3
"""Build the compact NOAA Niño 3.4/SOI time series used by the web app.

The inputs are NOAA PSL's standard-format monthly text files. NumPy is used
only while generating the TypeScript asset; the web application has no data
or Python runtime dependency.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import textwrap
from datetime import date
from pathlib import Path

import numpy as np


MISSING_VALUE = -99.99
NINO34_BANDWIDTH_C = 0.18
SOI_BANDWIDTH = 0.24


def read_psl_monthly(path: Path) -> dict[date, float]:
    lines = path.read_text(encoding="utf-8").splitlines()
    first_year, last_year = (int(value) for value in lines[0].split()[:2])
    values: dict[date, float] = {}
    for line in lines[1:]:
        fields = line.split()
        if len(fields) < 13:
            break
        try:
            year = int(fields[0])
            monthly = [float(value) for value in fields[1:13]]
        except ValueError:
            break
        if year < first_year or year > last_year:
            break
        for month, value in enumerate(monthly, start=1):
            if value != MISSING_VALUE:
                values[date(year, month, 1)] = value
    return values


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def next_month(month: date) -> date:
    if month.month == 12:
        return date(month.year + 1, 1, 1)
    return date(month.year, month.month + 1, 1)


def encode(values: np.ndarray) -> str:
    packed = np.asarray(values, dtype="<f4")
    return base64.b64encode(packed.tobytes()).decode("ascii")


def ts_chunks(encoded: str) -> str:
    return "\n".join(f'  "{chunk}",' for chunk in textwrap.wrap(encoded, 100))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("nino34", type=Path, help="NOAA PSL nino34.long.anom.data")
    parser.add_argument("soi", type=Path, help="NOAA PSL soi.long.data")
    parser.add_argument("output", type=Path, help="Generated TypeScript module")
    args = parser.parse_args()

    nino_by_month = read_psl_monthly(args.nino34)
    soi_by_month = read_psl_monthly(args.soi)
    months = sorted(nino_by_month.keys() & soi_by_month.keys())
    if not months:
        raise ValueError("The source files have no overlapping valid months")
    for previous, current in zip(months, months[1:]):
        if next_month(previous) != current:
            raise ValueError(f"The common time series has a gap after {previous:%Y-%m}")

    nino = np.array([nino_by_month[month] for month in months], dtype=np.float64)
    soi = np.array([soi_by_month[month] for month in months], dtype=np.float64)
    correlation = float(np.corrcoef(nino, soi)[0, 1])
    nino_p005, nino_p995 = np.quantile(nino, [0.005, 0.995])
    soi_p005, soi_p995 = np.quantile(soi, [0.005, 0.995])

    nino_histogram_domain = (
        float(nino.min() - 4 * NINO34_BANDWIDTH_C),
        float(nino.max() + 4 * NINO34_BANDWIDTH_C),
    )
    soi_histogram_domain = (
        float(soi.min() - 4 * SOI_BANDWIDTH),
        float(soi.max() + 4 * SOI_BANDWIDTH),
    )

    contents = f'''// Generated by scripts/prepare_noaa_enso.py. Do not edit by hand.
// Values are aligned monthly Float32 arrays from the common valid source span.

export const NOAA_ENSO_START = "{months[0]:%Y-%m}";
export const NOAA_ENSO_END = "{months[-1]:%Y-%m}";
export const NOAA_ENSO_MONTH_COUNT = {len(months)};
export const NOAA_NINO34_MEAN_C = {nino.mean():.9f};
export const NOAA_SOI_MEAN = {soi.mean():.9f};
export const NOAA_NINO34_SOI_CORRELATION = {correlation:.9f};
export const NOAA_NINO34_P005_C = {nino_p005:.9f};
export const NOAA_NINO34_P995_C = {nino_p995:.9f};
export const NOAA_SOI_P005 = {soi_p005:.9f};
export const NOAA_SOI_P995 = {soi_p995:.9f};
export const NOAA_NINO34_HISTOGRAM_DOMAIN: [number, number] = [{nino_histogram_domain[0]:.9f}, {nino_histogram_domain[1]:.9f}];
export const NOAA_SOI_HISTOGRAM_DOMAIN: [number, number] = [{soi_histogram_domain[0]:.9f}, {soi_histogram_domain[1]:.9f}];
export const NOAA_NINO34_BANDWIDTH_C = {NINO34_BANDWIDTH_C};
export const NOAA_SOI_BANDWIDTH = {SOI_BANDWIDTH};
export const NOAA_NINO34_SHA256 = "{sha256(args.nino34)}";
export const NOAA_SOI_SHA256 = "{sha256(args.soi)}";

export const NOAA_NINO34_BASE64 = [
{ts_chunks(encode(nino))}
].join("");

export const NOAA_SOI_BASE64 = [
{ts_chunks(encode(soi))}
].join("");
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(contents, encoding="utf-8")
    print(
        f"Wrote {args.output} with {len(months)} monthly pairs "
        f"from {months[0]:%Y-%m} through {months[-1]:%Y-%m}; "
        f"zero-lag correlation {correlation:.3f}."
    )


if __name__ == "__main__":
    main()
